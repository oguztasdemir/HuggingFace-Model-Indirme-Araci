CURRENT_LANGUAGE = "tr"

def get_lang():
    return CURRENT_LANGUAGE

def set_lang(lang_code):
    global CURRENT_LANGUAGE
    if lang_code in TRANSLATIONS:
        CURRENT_LANGUAGE = lang_code

def t(key, **kwargs):
    """
    Translates a key into the active language, formatting kwargs if provided.
    """
    lang_dict = TRANSLATIONS.get(CURRENT_LANGUAGE, TRANSLATIONS["tr"])
    text = lang_dict.get(key, TRANSLATIONS["tr"].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
